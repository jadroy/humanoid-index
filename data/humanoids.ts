export interface MediaItem {
  type: 'image' | 'video';
  url: string; // For images: path to file, For videos: path to MP4
  caption?: string;
  thumbnail?: string; // For videos, preview image
  position?: string; // CSS object-position override for this slide (falls back to humanoid-level)
  fit?: "contain" | "cover"; // CSS object-fit override for this slide
  credit?: { prefix?: string; name: string; href?: string }; // Source attribution rendered on the slide
}

export interface Humanoid {
  id: string;
  name: string;
  manufacturer: string;
  country?: string; // Origin country/region (e.g., "USA", "China", "Norway / USA"). Drives the Country stat row.
  useCase?: string; // Primary use case (e.g., "Home", "Industrial", "Research"). Drives the Use stat row.
  form?: "humanoid" | "semi" | "other"; // Body plan. Omit for a normal bipedal humanoid (the default).
  // "semi" = human-form upper body, no walking legs (wheeled base, static plinth).
  // "other" = not human-shaped at all. Drives the form filter chips above the wheel.
  drive?: string; // Drive/actuation/form-factor (e.g., "Electric", "Hydraulic", "Tendon-driven", "Wheeled base"). Drives the Drive stat row.
  year?: number;
  addedAt?: string; // ISO date the robot was added to the index (e.g. "2026-05-15"). Drives the "what's new" toast on the home page — entries within NEW_WINDOW_DAYS surface there. Set this on every new entry; omit for established robots (they won't toast).
  cost?: string; // Cost in a displayable format (e.g., "$50K", "$150K", "N/A")
  status?: "In Production" | "Prototype" | "Concept" | "Discontinued" | "Anticipated";
  availability?: "consumer" | "enterprise" | "research" | "prototype" | "discontinued"; // Drives the left-side label when there's no price (Enterprise only / Research only / etc.)
  height?: number; // in cm
  weight?: number; // in kg
  dof?: number; // degrees of freedom
  maxSpeed?: number; // m/s
  description?: string;
  imageUrl?: string; // Primary/cover image
  imagePosition?: string; // CSS object-position override (default: "center")
  imageFit?: "contain" | "cover"; // CSS object-fit override (default: "contain")
  imageScale?: number; // Multiplier applied to the rendered image (default: 1). Used for relative-size honesty between same-family variants.
  // Attribution for the cover image. Same shape MediaItem.credit uses, and it
  // renders the same way — set it only when the licence obliges us (a CC photo,
  // someone else's shot). Manufacturer press art carries no credit.
  imageCredit?: { prefix?: string; name: string; href?: string };
  logoUrl?: string; // Company logo
  manufacturerUrl?: string; // Company website (generic homepage)
  infoUrl?: string; // Specific product/info page — preferred Visit target when not for sale
  media?: MediaItem[]; // Additional images and videos
  purchaseUrl?: string; // Link to buy/learn more about the robot
  ogImageUrl?: string; // Custom share/OG card (1200×630, in /public). Overrides the generated /api/og/<id> card.
  sceneUrl?: string; // Optional scene/lifestyle image used as the stats column background
  scenePosition?: string; // CSS object-position for cropping the (landscape) scene into portrait tiles — anchors the crop on the robot (default "center")
  tags?: string[]; // Short descriptor chips — facets like use case, drive, vibe, reception (country lives on its own `country` field now)
  // Extended engineering specs surfaced when the stats column is in Engineer mode
  // (toggle persists in localStorage). All fields optional — missing rows render as
  // a dimmed em-dash so cards stay vertically aligned across robots.
  engineering?: {
    // Motion & strength
    payload?: number;             // kg — total carrying capacity
    reach?: number;               // cm — typical arm reach
    liftPerArm?: number;          // kg — per-arm lift
    peakTorque?: number;          // Nm — peak joint torque
    walkSpeed?: number;           // m/s — nominal walking speed (separate from maxSpeed)
    // Power
    runtime?: number;             // hours — single-charge runtime
    batteryCapacity?: number;     // kWh
    batteryVoltage?: number;      // V
    chargeTime?: number;          // minutes — full charge time
    swappableBattery?: boolean;
    // Joints
    handDof?: number;             // DOF per hand
    armDof?: number;              // DOF per arm
    legDof?: number;              // DOF per leg
    // Actuation
    actuators?: string;           // e.g. "BLDC + harmonic drive"
    // Sensing
    cameras?: string;             // e.g. "4× RGB, 2× depth"
    lidar?: string;               // e.g. "Velodyne VLP-16" or omit
    imu?: string;                 // e.g. "9-axis"
    microphones?: number;
    forceSensors?: boolean;
    // Compute & software
    compute?: string;             // e.g. "NVIDIA Jetson Orin NX"
    software?: string;            // e.g. "ROS2"
    teleop?: boolean;
    // Environment
    ipRating?: string;            // e.g. "IP54"
    operatingTemp?: string;       // e.g. "0–40°C"
    noiseLevel?: number;          // dB
    // Connectivity
    connectivity?: string;        // e.g. "WiFi 6 / 5G / Ethernet"
  };
}

