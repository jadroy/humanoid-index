  weight?: number; // in kg
  dof?: number; // degrees of freedom
  maxSpeed?: number; // m/s
  description?: string;
  imageUrl?: string; // Primary/cover image
  imagePosition?: string; // CSS object-position override (default: "center")
  imageFit?: "contain" | "cover"; // CSS object-fit override (default: "contain")
