// The whole index reads newest-first, and the Other lane stays pinned behind the
// figures. Pending entries have to merge into that order rather than sit in front
// of it — prepending them put the 2025 wave ahead of A3 (2026) on localhost only,
// so dev showed an order production never had.
function byYearDesc(list: Humanoid[]): Humanoid[] {
  const rank = (h: Humanoid) => (h.form === "other" ? 1 : 0);
  return [...list].sort(
    (a, b) => rank(a) - rank(b) || (b.year ?? 0) - (a.year ?? 0)
  );
}

export const humanoids: Humanoid[] = SHOW_PENDING_IMAGE_ENTRIES
  ? byYearDesc([...visibleHumanoids, ...pendingImageHumanoids])
  : visibleHumanoids;
